#!/usr/bin/env python3
"""Generate report/sm_charges.tex from the sympy model and compile it with pdflatex.

    python3 lisi/make_report.py

Every number in the PDF is computed by sm_charges.build(); sympy.latex renders
the rationals, vectors and exact sums.  Requires sympy and pdflatex.
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path
import shutil
import subprocess
import sys

import sympy as sp

from e8 import require
from sm_charges import NAMES_16, SM_10, SM_16, build, content

HERE = Path(__file__).resolve().parent
OUT = HERE / "report"
NAMES_10 = {
    ("3", 1, sp.Rational(-1, 3)): "D",
    ("3b", 1, sp.Rational(1, 3)): "D^c",
    ("1", 2, sp.Rational(1, 2)): "H_u",
    ("1", 2, sp.Rational(-1, 2)): "H_d",
}
REP = {"3": r"\mathbf{3}", "3b": r"\overline{\mathbf{3}}", "1": r"\mathbf{1}"}


def L(x) -> str:
    return sp.latex(x)


def rep_label(color: str, su2: int) -> str:
    return "(" + REP[color] + r",\mathbf{" + str(su2) + "})"


def table(records, names) -> str:
    groups = defaultdict(list)
    for r in records:
        groups[(r["color"], r["su2"], r["Y"])].append(r)
    rows = []
    for key in sorted(groups, key=lambda k: (-len(groups[k]), str(k))):
        recs = groups[key]
        qs = sorted({r["Q"] for r in recs})
        row = "$" + names[key].replace("nu", r"\nu ") + "$ & $" + rep_label(key[0], key[1]) + "$ & $" + L(key[2]) + "$ & $"
        row += ",\\ ".join(L(q) for q in qs) + "$ & " + str(len(recs)) + r" \\"
        rows.append(row)
    head = (
        "\\begin{tabular}{llccr}\n\\toprule\n"
        "field & $\\mathrm{SU}(3)_c\\times\\mathrm{SU}(2)_L$ & $Y$ & $Q=T_3+Y$ & weights \\\\\n\\midrule\n"
    )
    return head + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}"


def anomaly_line(records, power: int) -> str:
    groups = defaultdict(int)
    for r in records:
        groups[r["Y"]] += 1
    terms = [sp.Mul(n, sp.Pow(y, power), evaluate=False) for y, n in sorted(groups.items())]
    total = sp.Add(*[sp.Mul(n, sp.Pow(y, power)) for y, n in groups.items()])
    require(total == 0, total)
    return L(sp.Add(*terms, evaluate=False)) + " = " + L(total)


def build_tex() -> str:
    m = build()
    f16, f10, f1 = m.families["16"], m.families["10"], m.families["1"]
    require(dict(content(f16)) == SM_16 and dict(content(f10)) == SM_10, "model drifted")

    return r"""\documentclass[11pt]{article}
\usepackage[margin=0.9in]{geometry}
\usepackage{amsmath,amssymb,booktabs}
\usepackage[hidelinks]{hyperref}
\title{Standard Model quantum numbers from the $E_6\times SU(3)$ chirality pair}
\author{Generated by \texttt{lisi/make\_report.py} (sympy $%s$)}
\date{}
\begin{document}
\maketitle

\begin{abstract}
Starting only from the 240 roots of $E_8$, we recover the branching
$27\to 1+16+10$ under $SO(10)\times U(1)$, the Standard Model content of the
$16$, the hypercharge generator, and the vanishing of the linear and cubic
$U(1)$ sums.  Every statement is an exact rational computation; see the
scripts in \texttt{lisi/}.  Nothing here is a derivation of the physical
Standard Model, only a check that the chirality-theorem pair contains it.
\end{abstract}

\section{Setup}
Roots of $E_8$ are stored in doubled integer coordinates.  The horizontal
$SU(3)_M$ is the $A_2$ spanned by two roots with inner product $-1$, and
$E_6$ is its centralizer.  The $240$ roots split as $72+6+6\cdot27$, the root
form of
\[
  248=(78,1)+(1,8)+(27,3)+(\overline{27},\bar 3).
\]

\section{From $E_6$ to $SO(10)$}
Fix one weight $w_0$ of the $27$ (in true coordinates, $\langle w_0,w_0\rangle=%s$):
\[
  w_0=%s .
\]
The $E_6$ roots orthogonal to $w_0$ form a system of $%d$ roots, that of
$SO(10)$, and the $27$ splits by $\langle w,w_0\rangle$:
\[
  27 = \underbrace{\mathbf{1}}_{4/3}\;+\;\underbrace{\mathbf{16}}_{1/3}\;+\;\underbrace{\mathbf{10}}_{-2/3}.
\]

\section{Standard Model content}
Inside $SO(10)$ we select an $A_2\times A_1$ subsystem (roots $a,b$ and $g$)
for which the $16$ branches as one Standard Model generation:
\[
  a=%s,\quad b=%s,\quad g=%s .
\]
The hypercharge generator is the vector orthogonal to $A_2\times A_1$, to
$w_0$ and to the horizontal $A_2$ that reproduces the Standard Model
values; a weight $w$ has $Y=\langle w,Y\rangle$ and $T_3=\langle w,g\rangle/2$ with
\[
  Y=%s .
\]
\subsection*{The $\mathbf{16}$}
\begin{center}
%s
\end{center}
\subsection*{The $\mathbf{10}$ and the singlet}
\begin{center}
%s
\end{center}
The singlet has $Y=%s$ and $Q=%s$.

\paragraph{Cross-check.}  On the $40$ roots of $SO(10)$ this $Y$ takes the
values of the $SU(5)$ adjoint pattern: eight roots at $0$, twelve at $\pm5/6$,
twelve at $\pm1/6$, six at $\pm2/3$ and two at $\pm1$.  This is the standard
hypercharge, not a flipped one.

\section{Anomaly sums}
Exact sums over the $\mathbf{16}$:
\begin{align*}
  \sum Y &= %s,\\
  \sum Y^3 &= %s .
\end{align*}
The $\mathbf{10}$ is vector-like, so its sums vanish termwise; the $\mathbf{1}$
carries $Y=0$.  The sums $\sum Q$ and $\sum Q^3$ over the $16$ also vanish, as
the scripts verify.  This is the Standard Model gauge-anomaly cancellation
within a single generation, visible here as a property of the $E_6$ weights.

\section{Three families and triality}
In the chirality theorem the representation is $V=27\boxtimes 3$, so the net
chiral content is three copies of $16$, i.e.\ $48$ Weyl fermions, together with
three vector-like $10$'s and three singlets.  A separate check places the second
$D_4$ of $D_4\times D_4\subset E_8$ inside $E_6$, giving
$27=8_v+8_s+8_c+3\cdot\mathbf 1$, the triality triple used by Lisi for
generations.  Whether the horizontal $3$ and the triality $3$ are related is an
open question that these computations do not settle.

\section{Reproducing}
\begin{verbatim}
python3 lisi/run_all.py          # all checks
python3 lisi/make_report.py      # regenerate this PDF
\end{verbatim}
\end{document}
""" % (
        sp.__version__,
        L(sp.Rational(4, 3)),
        L(m.w0.T),
        len(m.d5_roots),
        L(m.a.T), L(m.b.T), L(m.g.T),
        L(m.Y.T),
        table(f16, NAMES_16),
        table(f10, NAMES_10),
        L(f1[0]["Y"]), L(f1[0]["Q"]),
        anomaly_line(f16, 1),
        anomaly_line(f16, 3),
    )


def main() -> int:
    if shutil.which("pdflatex") is None:
        print("pdflatex not found")
        return 1
    OUT.mkdir(exist_ok=True)
    tex = OUT / "sm_charges.tex"
    tex.write_text(build_tex(), encoding="utf-8")
    for _ in range(2):
        r = subprocess.run(
            ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", tex.name],
            cwd=OUT, text=True, capture_output=True, check=False,
        )
        if r.returncode != 0:
            print(r.stdout[-3000:])
            return 1
    for ext in ("aux", "log", "out"):
        (OUT / f"sm_charges.{ext}").unlink(missing_ok=True)
    print(f"PASS  wrote {tex.relative_to(HERE.parent)} and sm_charges.pdf")
    return 0


if __name__ == "__main__":
    sys.exit(main())
